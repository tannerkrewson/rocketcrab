#!/usr/bin/env node
/**
 * Generates the before/after tables in docs/testing/large-room-load.md from
 * two in-process simulation samples (docs/testing/large-room-sim-*.json).
 *
 * Usage: node scripts/large-room-table.mjs <before.json> <after.json> <doc.md>
 *
 * The tables are written between the markers
 * `<!-- large-room-table:start -->` and `<!-- large-room-table:end -->`, so the
 * numbers are never typed by hand. Projections exclude WebRTC framing, as the
 * doc states. Pure Node built-ins; no dependencies.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const SIZES = [10, 25, 50, 100, 200];
const ACTIONS_PER_SECOND = 5;

function load(path) {
  const report = JSON.parse(readFileSync(path, "utf8"));
  const bySize = new Map();
  for (const result of report.results) {
    bySize.set(result.players, result.summary);
  }
  return { name: basename(path), date: report.date, bySize };
}

function summaryFor(sample, size) {
  const summary = sample.bySize.get(size);
  if (summary === undefined) {
    throw new Error(`${sample.name} has no ${size}-player result`);
  }
  return summary;
}

/** Mbit/s from bytes per action at a given action rate (projected, no framing). */
function mbitPerSecond(bytesPerAction, actionsPerSecond) {
  return (bytesPerAction * actionsPerSecond * 8) / 1_000_000;
}

function fmtInt(value) {
  return Math.round(value).toLocaleString("en-US");
}

function fmtOne(value) {
  return value.toFixed(1);
}

function fmtChange(before, after) {
  const pct = ((after - before) / before) * 100;
  return `${pct >= 0 ? "+" : ""}${pct.toFixed(1)}%`;
}

function render(before, after) {
  const lines = [];
  lines.push(
    `Generated by \`scripts/large-room-table.mjs\` from \`${before.name}\` (before) and \`${after.name}\` (after). Both are single-process in-process simulation runs, not WebRTC measurements.`,
    "",
    "Authority traffic per action (measured bytes are JSON of the approximate envelope plus payload):",
    "",
    "| Players | Authority bytes/action before | after | change | Authority msgs/action before | after | Dispatcher bytes/action before | after |",
    "| ------: | ----------------------------: | ----: | -----: | --------------------------: | ----: | -----------------------------: | ----: |",
  );
  for (const size of SIZES) {
    const b = summaryFor(before, size);
    const a = summaryFor(after, size);
    lines.push(
      `| ${size} | ${fmtInt(b.authorityBytesPerAction)} | ${fmtInt(a.authorityBytesPerAction)} | ${fmtChange(b.authorityBytesPerAction, a.authorityBytesPerAction)} | ${fmtOne(b.authorityMessagesPerAction)} | ${fmtOne(a.authorityMessagesPerAction)} | ${fmtInt(b.dispatcherBytesPerAction)} | ${fmtInt(a.dispatcherBytesPerAction)} |`,
    );
  }
  lines.push(
    "",
    "Snapshot bytes per action, summed over every copy sent (history = processed-action IDs; state body = canonical state):",
    "",
    "| Players | History bytes/action before | after | State body bytes/action before | after |",
    "| ------: | --------------------------: | ----: | -----------------------------: | ----: |",
  );
  for (const size of SIZES) {
    const b = summaryFor(before, size);
    const a = summaryFor(after, size);
    lines.push(
      `| ${size} | ${fmtInt(b.authoritySnapshotHistoryBytesPerAction)} | ${fmtInt(a.authoritySnapshotHistoryBytesPerAction)} | ${fmtInt(b.authoritySnapshotStateBytesPerAction)} | ${fmtInt(a.authoritySnapshotStateBytesPerAction)} |`,
    );
  }
  lines.push(
    "",
    `Projected uplink at ${ACTIONS_PER_SECOND} actions/s (**projected, excluding framing**: WebRTC, SCTP, DTLS and Trystero overhead are not included, so real totals are higher):`,
    "",
    "| Players | Authority Mbit/s before | after | Dispatcher Mbit/s before | after |",
    "| ------: | ----------------------: | ----: | -----------------------: | ----: |",
  );
  for (const size of SIZES) {
    const b = summaryFor(before, size);
    const a = summaryFor(after, size);
    lines.push(
      `| ${size} | ${fmtOne(mbitPerSecond(b.authorityBytesPerAction, ACTIONS_PER_SECOND))} | ${fmtOne(mbitPerSecond(a.authorityBytesPerAction, ACTIONS_PER_SECOND))} | ${mbitPerSecond(b.dispatcherBytesPerAction, ACTIONS_PER_SECOND).toFixed(2)} | ${mbitPerSecond(a.dispatcherBytesPerAction, ACTIONS_PER_SECOND).toFixed(2)} |`,
    );
  }
  return lines.join("\n");
}

function main() {
  const [beforePath, afterPath, docPath, section = "large-room-table"] = process.argv.slice(2);
  if (!beforePath || !afterPath || !docPath) {
    process.stderr.write(
      "usage: large-room-table.mjs <before.json> <after.json> <doc.md> [section]\n",
    );
    process.exit(2);
  }
  const START = `<!-- ${section}:start -->`;
  const END = `<!-- ${section}:end -->`;
  const before = load(beforePath);
  const after = load(afterPath);
  const table = render(before, after);
  const doc = readFileSync(docPath, "utf8");
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${docPath} must contain ${START} and ${END} in order`);
  }
  const updated = doc.slice(0, start + START.length) + "\n" + table + "\n" + doc.slice(end);
  writeFileSync(docPath, updated);
  process.stdout.write(`wrote ${SIZES.length} sizes to ${docPath}\n`);
}

main();
